const JS_CORE = "js/core/src/generated";
const jsHeader = (sources) =>
  `// GENERATED by shared/scripts/generate.mjs — do not edit.\n// Sources: ${sources.join(", ")}\n`;
const jsKey = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
const jsLiteral = (value) =>
  Array.isArray(value)
    ? `[${value.map(jsLiteral).join(", ")}]`
    : value !== null && typeof value === "object"
      ? `{ ${Object.entries(value).map(([k, v]) => `${jsKey(k)}: ${jsLiteral(v)}`).join(", ")} }`
      : JSON.stringify(value);

// JavaScript runs the reference itself instead of a port: swap its CommonJS tail for ES exports.
function emitJsReference() {
  const tail = /\nif \(typeof module !== "undefined"\) \{\n\s*module\.exports = \{([^}]*)\};\n\}\n?$/.exec(referenceSource);
  if (!tail) throw new Error(`${REFERENCE}: expected the file to end with its module.exports block`);
  const names = tail[1].split(",").map((n) => n.trim()).filter((n) => n && n !== "CHORDS");
  return `// @ts-nocheck\n${jsHeader([REFERENCE])}// Plain JavaScript; typed by ../layout.ts.\n\n${referenceSource.slice(0, tail.index)}\nexport { ${names.join(", ")} };\n`;
}

function emitJsLibrary() {
  if (library.some(({ id }) => id === "all")) throw new Error(`chords.json: id "all" is reserved for ChordLibrary.all`);
  const chords = library.map(({ id, ...chord }) => `  ${id}: ${jsLiteral(chord)},`).join("\n");
  return `${jsHeader(["shared/data/chords.json"])}
import type { Chord } from "../types.js";

export type ChordId = ${library.map(({ id }) => JSON.stringify(id)).join(" | ")};

export interface ChordLibraryEntry {
  readonly id: ChordId;
  readonly chord: Chord;
}

const chords = {
${chords}
} satisfies Record<ChordId, Chord>;

/** The shared chord library. Keys match the ids in chords.json; \`all\` lists every chord in library order. */
export const ChordLibrary: { readonly [K in ChordId]: Chord } & { readonly all: readonly ChordLibraryEntry[] } = {
  ...chords,
  all: (Object.keys(chords) as ChordId[]).map((id) => ({ id, chord: chords[id] })),
};
`;
}

function emitJsTokens() {
  const { $comment, ...rest } = tokens;
  const body = JSON.stringify(rest, null, 2).replace(/^(\s*)"([A-Za-z_$][\w$]*)":/gm, "$1$2:");
  return `${jsHeader(["shared/data/tokens.json"])}
/** Colors, accents, fonts, type and spacing around the diagram. Colors are sRGB hex, sizes px (dp on native), tracking and line height em. */
export const ChordTokens = ${body} as const;
`;
}

function emitJs() {
  return {
    [`${JS_CORE}/reference.ts`]: emitJsReference(),
    [`${JS_CORE}/library.ts`]: emitJsLibrary(),
    [`${JS_CORE}/tokens.ts`]: emitJsTokens()
  };
}

// ---------------------------------------------------------------------------
// Write / check
// ---------------------------------------------------------------------------

const emitters = { golden: emitGolden, fuzz: emitFuzz, swift: emitSwift, kotlin: emitKotlin, js: emitJs, docs: emitDocs };
const outputs = Object.assign({}, ...Object.values(emitters).map((emit) => emit()));
const check = process.argv.includes("--check");
const stale = [];

for (const [path, content] of Object.entries(outputs)) {
  const abs = join(root, path);
  const next = Buffer.isBuffer(content) ? content : Buffer.from(content, "utf8");
  let current = null;
  try {
    current = readFileSync(abs);
  } catch {}
  if (current && current.equals(next)) continue;
  stale.push(path);
  if (!check) {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, next);
  }
}

if (check && stale.length) {
  console.error(`Generated files are stale — run \`npm run generate\`:\n${stale.map((p) => `  ${p}`).join("\n")}`);
  process.exit(1);
}
console.log(stale.length ? `${check ? "stale" : "wrote"}:\n${stale.map((p) => `  ${p}`).join("\n")}` : "generated files up to date");
