const issueRefs = (chord) => ref.validateChord(chord).map(({ code, path }) => ({ code, path }));

function emitGolden() {
  const cases = [
    ...library.map(({ id, ...chord }) => ({ id: `library/${id}`, chord, options: {} })),
    ...extraCases.map((c) => ({ id: `case/${c.id}`, chord: c.chord, options: c.options ?? {} })),
    ...invalidCases.map((c) => ({ id: `invalid/${c.id}`, chord: c.chord, options: c.options ?? {} }))
  ].map((c) => {
    const layout = ref.layoutChord(c.chord, c.options);
    return { ...c, layout, svg: ref.toSvg(layout, 1), description: ref.describeChord(c.chord), issues: issueRefs(c.chord) };
  });
  const doc = {
    $comment: `GENERATED by shared/scripts/generate.mjs from ${REFERENCE} — do not edit. Every platform port must reproduce these layouts (within 1e-9), SVG strings and descriptions (exactly), and validation issues (code and path).`,
    cases
  };
  return { "shared/fixtures/golden.json": JSON.stringify(doc, null, 2) + "\n" };
}

// ---------------------------------------------------------------------------
// Fuzz fixtures: seeded random chords, valid and malformed
// ---------------------------------------------------------------------------

const FUZZ_SEED = 20260914;
const FUZZ_CASES = 400;

function mulberry32(seed) {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// FNV-1a 64 over UTF-8, so a port can check a whole SVG against one short string
function fnv1a64(text) {
  let hash = 0xcbf29ce484222325n;
  for (const byte of Buffer.from(text, "utf8")) {
    hash ^= BigInt(byte);
    hash = (hash * 0x100000001b3n) & 0xffffffffffffffffn;
  }
  return hash.toString(16).padStart(16, "0");
}

function emitFuzz() {
  const random = mulberry32(FUZZ_SEED);
  const int = (lo, hi) => lo + Math.floor(random() * (hi - lo + 1));
  const pick = (items) => items[int(0, items.length - 1)];
  const cases = [];
  for (let n = 0; n < FUZZ_CASES; n++) {
    const strings = pick([6, 6, 6, 6, 6, 4, 4, 5, 7, 8, 12, 2, 1, 0, 13]);
    const base = int(0, 22);
    const reach = pick([2, 3, 3, 4, 5, 7, 11, 16]);
    const frets = Array.from({ length: strings }, () => {
      const r = random();
      if (r < 0.14) return -1;
      if (r < 0.28) return 0;
      if (r < 0.31) return pick([-3, -2, 100, 140]);
      return Math.max(1, base + int(0, reach));
    });
    const chord = {};
    if (random() < 0.6) chord.name = `Fuzz ${n}`;
    chord.frets = frets;
    if (random() < 0.7) {
      const length = random() < 0.1 ? int(0, strings + 2) : strings;
      chord.fingers = Array.from({ length }, () => pick([0, 0, 1, 2, 3, 4, 5, 6, -1]));
    }
    if (random() < 0.35) {
      const fretted = frets.filter((f) => f > 0 && f <= ref.M.MAX_FRET);
      const fret = fretted.length && random() < 0.8 ? pick(fretted) : int(0, 30);
      chord.barre = { fret, from: int(-1, strings), to: int(-1, strings) };
      if (random() < 0.6) chord.barre.finger = pick([1, 1, 2, 0, 5, 9]);
    }
    if (random() < 0.15) chord.caption = random() < 0.5 ? "" : `caption ${n}`;
    if (random() < 0.12) {
      chord.tuning = Array.from({ length: random() < 0.8 ? strings : strings + 1 }, (_, i) => (random() < 0.05 ? "" : `S${i}`));
    }
    const options = random() < 0.2 ? { showFingers: false } : {};
    const layout = ref.layoutChord(chord, options);
    cases.push({
      chord,
      options,
      position: layout.position,
      rows: layout.rows,
      strings: layout.strings,
      svgFnv1a64: fnv1a64(ref.toSvg(layout, 1)),
      description: ref.describeChord(chord),
      issues: issueRefs(chord)
    });
  }
  const comment = `GENERATED by shared/scripts/generate.mjs (seed ${FUZZ_SEED}) from ${REFERENCE} — do not edit. Random chords, valid and malformed. Every port must reproduce each case's position, rows, strings, description and issues, and the FNV-1a 64 hash of its SVG.`;
  const body = cases.map((c) => `    ${JSON.stringify(c)}`).join(",\n");
  return { "shared/fixtures/fuzz.json": `{\n  "$comment": ${JSON.stringify(comment)},\n  "cases": [\n${body}\n  ]\n}\n` };
}

