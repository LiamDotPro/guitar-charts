const FIGURES = "shared/docs/figures.json";
const ANDROID_REFERENCES = "kotlin/chord-diagram-compose/src/screenshotTestDebug/reference/com/guitarcharts/chord/compose";
const figures = readJson(FIGURES);
const libraryChords = Object.fromEntries(library.map(({ id, ...chord }) => [id, chord]));
const accentsById = Object.fromEntries(tokens.accents.map((a) => [a.id, a]));
const SANS = "Helvetica Neue, Helvetica, Arial, sans-serif";
const MONO = "IBM Plex Mono, ui-monospace, monospace";
const xmlText = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const r2 = (n) => Math.round(n * 100) / 100;
// the diagram's own primitives, without the outer <svg> element
const svgInner = (layout) => ref.toSvg(layout, 1).replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");

function figureChord(value, where) {
  const chord = typeof value === "string" ? libraryChords[value] : value;
  if (!chord) throw new Error(`${FIGURES} ${where}: unknown chord id "${value}"`);
  validateChord(`${FIGURES} ${where}`, chord);
  if (errors.length) throw new Error(errors.join("\n"));
  return chord;
}

function svgDocument(width, height, title, body) {
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" role="img" aria-label="${xmlText(title)}">` +
    `<title>${xmlText(title)}</title>` +
    `<rect x="0.5" y="0.5" width="${width - 1}" height="${height - 1}" rx="14" fill="${tokens.palette.paper}" stroke="${tokens.colors.rule}"/>` +
    body +
    `</svg>\n`
  );
}

// One ChordCard (diagram, name, caption, optional export link) with the web component's spacing.
const CARD = { width: 174, padX: 14, padTop: 20, padBottom: 18, gap: 12, nameLine: 19, labelGap: 3, captionLine: 13, link: 18 };
const cardHeight = (withLink) =>
  CARD.padTop + ref.M.HEIGHT + CARD.gap + CARD.nameLine + CARD.labelGap + CARD.captionLine + (withLink ? CARD.link : 0) + CARD.padBottom;

function cardSvg(cell, x, y, where) {
  const chord = { ...figureChord(cell.chord, where) };
  if (cell.name != null) chord.name = cell.name;
  if (cell.caption != null) chord.caption = cell.caption;
  const options = { ...(cell.options ?? {}) };
  if (cell.accent) {
    if (!accentsById[cell.accent]) throw new Error(`${FIGURES} ${where}: unknown accent "${cell.accent}"`);
    options.accent = accentsById[cell.accent].hex;
  }
  const layout = ref.layoutChord(chord, options);
  const centerX = r2(x + CARD.width / 2);
  const nameY = y + CARD.padTop + ref.M.HEIGHT + CARD.gap + 15;
  const captionY = nameY + CARD.labelGap + CARD.captionLine + 1;
  const parts = [
    `<g transform="translate(${r2(x + CARD.padX)} ${r2(y + CARD.padTop)})">${svgInner(layout)}</g>`,
    `<text x="${centerX}" y="${r2(nameY)}" text-anchor="middle" font-family="${SANS}" font-size="15" font-weight="600" fill="${tokens.colors.name}">${xmlText(layout.name)}</text>`,
    `<text x="${centerX}" y="${r2(captionY)}" text-anchor="middle" font-family="${MONO}" font-size="10" letter-spacing="0.8" fill="${tokens.palette.muted}">${xmlText(layout.caption.toUpperCase())}</text>`
  ];
  if (cell.download) {
    const label = `${cell.download} ↓`.toUpperCase();
    const linkY = captionY + CARD.link;
    const width = label.length * (9.5 * 0.6 + 0.76);
    parts.push(
      `<text x="${centerX}" y="${r2(linkY)}" text-anchor="middle" font-family="${MONO}" font-size="9.5" letter-spacing="0.76" fill="${tokens.palette.muted}">${xmlText(label)}</text>`,
      `<rect x="${r2(centerX - width / 2)}" y="${r2(linkY + 3)}" width="${r2(width)}" height="1" fill="${tokens.colors.underline}"/>`
    );
  }
  return parts.join("");
}

function gridFigure(id, grid) {
  const PAD = 24, GAP_X = 4, GAP_Y = 8;
  const withLink = grid.cells.some((c) => c.download);
  const rows = Math.ceil(grid.cells.length / grid.columns);
  const width = PAD * 2 + grid.columns * CARD.width + (grid.columns - 1) * GAP_X;
  const height = PAD * 2 + rows * cardHeight(withLink) + (rows - 1) * GAP_Y;
  const body = grid.cells
    .map((cell, i) =>
      cardSvg(cell, PAD + (i % grid.columns) * (CARD.width + GAP_X), PAD + Math.floor(i / grid.columns) * (cardHeight(withLink) + GAP_Y), `grids.${id}[${i}]`)
    )
    .join("");
  return svgDocument(width, height, grid.title, body);
}

// A large diagram with callouts whose leader lines point at the real primitives.
function anatomyFigure(spec) {
  const chord = figureChord(spec.chord, "anatomy");
  const layout = ref.layoutChord(chord);
  const S = 2.6, W = 860, TOP = 34;
  const gridCenter = (ref.stringX(0) + ref.stringX(ref.M.STRINGS - 1)) / 2;
  const dx = W / 2 - gridCenter * S;
  const X = (x) => r2(dx + x * S);
  const Y = (y) => r2(TOP + y * S);
  const leftEdge = r2(dx - 34);
  const rightEdge = r2(dx + (ref.stringX(ref.M.STRINGS - 1) + ref.M.DOT_R) * S + 70);

  const find = (list, id) => {
    const hit = list.find((p) => p.id === id);
    if (!hit) throw new Error(`${FIGURES} anatomy: chord has no "${id}" to label`);
    return hit;
  };
  const mute = find(layout.lines, "mute");
  const open = find(layout.circles, "open");
  const dot = find(layout.circles, "dot");
  const barre = find(layout.rects, "barre");
  const position = find(layout.texts, "position");
  const stringOf = (x) => Math.round((x - ref.M.LEFT) / ref.M.SPACING);
  const barreIn = chord.barre;

  const callout = (side, targetX, targetY, title, detail) => {
    const labelX = side === "left" ? leftEdge : rightEdge;
    const lineFrom = side === "left" ? labelX + 10 : labelX - 10;
    const anchor = side === "left" ? "end" : "start";
    return (
      `<line x1="${lineFrom}" y1="${targetY}" x2="${targetX}" y2="${targetY}" stroke="${tokens.palette.line}" stroke-width="1"/>` +
      `<circle cx="${targetX}" cy="${targetY}" r="2.6" fill="${tokens.palette.ink}"/>` +
      `<text x="${labelX}" y="${r2(targetY - 5)}" text-anchor="${anchor}" font-family="${MONO}" font-size="11" letter-spacing="1.4" fill="${tokens.colors.link}">${xmlText(title)}</text>` +
      `<text x="${labelX}" y="${r2(targetY + 14)}" text-anchor="${anchor}" font-family="${MONO}" font-size="12" fill="${tokens.colors.body}">${xmlText(detail)}</text>`
    );
  };

  const parts = [`<g transform="translate(${r2(dx)} ${TOP}) scale(${S})">${svgInner(layout)}</g>`];
  parts.push(
    callout("left", r2(X(Math.min(mute.x1, mute.x2)) - 6), Y(ref.M.MARKER_Y), "MUTED STRING", `frets[${stringOf(mute.x1 + ref.M.MUTE_HALF)}] = -1`),
    callout("left", r2(X(position.x - 20) - 4), Y(position.y), "FRET WINDOW", `starts at fret ${layout.position}`),
    callout("right", r2(X(open.cx + open.r) + 6), Y(open.cy), "OPEN STRING", `frets[${stringOf(open.cx)}] = 0`),
    callout("right", r2(X(dot.cx + dot.r) + 6), Y(dot.cy), "FINGER NUMBER", `fingers[${stringOf(dot.cx)}] = ${chord.fingers[stringOf(dot.cx)]}`),
    callout("right", r2(X(barre.x + barre.w) + 6), Y(barre.y + barre.h / 2), "BARRE", `fret ${barreIn.fret}, strings ${barreIn.from}–${barreIn.to}`)
  );

  const namesY = Y(ref.M.HEIGHT) + 24;
  ["E", "A", "D", "G", "B", "e"].forEach((n, i) =>
    parts.push(`<text x="${X(ref.stringX(i))}" y="${r2(namesY)}" text-anchor="middle" font-family="${MONO}" font-size="13" fill="${tokens.palette.muted}">${n}</text>`)
  );
  const nameY = namesY + 42;
  parts.push(
    `<text x="${X(gridCenter)}" y="${r2(nameY)}" text-anchor="middle" font-family="${SANS}" font-size="22" font-weight="600" fill="${tokens.colors.name}">${xmlText(layout.name)}</text>`,
    `<text x="${X(gridCenter)}" y="${r2(nameY + 22)}" text-anchor="middle" font-family="${MONO}" font-size="12" letter-spacing="1" fill="${tokens.palette.muted}">${xmlText(layout.caption.toUpperCase())}</text>`
  );
  return svgDocument(W, Math.ceil(nameY + 48), spec.title, parts.join(""));
}

function emitDocs() {
  const out = {};
  for (const [id, grid] of Object.entries(figures.grids)) out[`docs/images/${id}.svg`] = gridFigure(id, grid);
  out["docs/images/anatomy.svg"] = anatomyFigure(figures.anatomy);

  // the exact file ChordExporter writes, byte for byte
  const exportChord = figureChord(figures.export.chord, "export");
  out[`docs/images/export-${figures.export.chord.toLowerCase()}.svg`] = ref.toSvg(ref.layoutChord(exportChord), figures.export.scale);

  for (const [name, key] of Object.entries(figures.android)) {
    const [folder, fn] = key.split("/");
    const dir = join(root, ANDROID_REFERENCES, folder);
    const matches = existsSync(dir) ? readdirSync(dir).filter((f) => f.startsWith(`${fn}_`) && f.endsWith(".png")) : [];
    if (matches.length !== 1) {
      throw new Error(`${FIGURES} android.${name}: expected 1 screenshot reference for ${key}, found ${matches.length}. Run ./gradlew :chord-diagram-compose:updateDebugScreenshotTest and delete stale references.`);
    }
    out[`docs/images/android/${name}.png`] = readFileSync(join(dir, matches[0]));
  }
  return out;
}

