// the SwiftUI target only exists on Apple platforms; keep `swift test` working on Linux
function swiftUIOnly(source) {
  const lines = source.split("\n");
  const header = lines.slice(0, 2).join("\n");
  const body = lines.slice(2).join("\n").trim();
  return `${header}\n\n#if canImport(SwiftUI)\n${body}\n#endif\n`;
}

function emitSwift() {
  return {
    "swift/Sources/ChordDiagramCore/Generated/ChordMetrics.generated.swift": emitSwiftMetrics(),
    "swift/Sources/ChordDiagramCore/Generated/ChordLibrary.generated.swift": emitSwiftLibrary(),
    "swift/Sources/ChordDiagram/Generated/ChordTokens.generated.swift": swiftUIOnly(emitSwiftTokens())
  };
}

