const camel = (s) => s.toLowerCase().replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const lowerFirst = (s) => s.charAt(0).toLowerCase() + s.slice(1);
const swiftString = (s) => JSON.stringify(s).replace(/\\u([0-9a-fA-F]{4})/g, "\\u{$1}");
const swiftHeader = (sources) =>
  `// GENERATED by shared/scripts/generate.mjs — do not edit.\n// Sources: ${sources.join(", ")}\n`;

// pull the trailing `// comment` for each key out of the reference so docs follow the numbers
function referenceComments(objectName) {
  const block = new RegExp(`const ${objectName} = \\{([\\s\\S]*?)\\n\\};`).exec(referenceSource)?.[1] ?? "";
  const out = {};
  for (const line of block.split("\n")) {
    const m = /^\s*([A-Za-z_0-9]+):[^/]*(?:\/\/\s*(.*))?$/.exec(line);
    if (m && m[2]) out[m[1]] = m[2].trim();
  }
  return out;
}

const INT_METRICS = new Set(["SPAN", "STRINGS", "MIN_STRINGS", "MAX_STRINGS", "MAX_ROWS", "MAX_FRET", "THUMB"]);

function emitSwiftMetrics() {
  const metricDocs = referenceComments("M");
  const paletteDocs = referenceComments("PALETTE");
  const doc = (text) => (text ? `    /// ${text}\n` : "");
  const metrics = Object.entries(ref.M)
    .map(([k, v]) => `${doc(metricDocs[k])}    public static let ${camel(k)}: ${INT_METRICS.has(k) ? "Int" : "Double"} = ${v}`)
    .join("\n");
  const palette = Object.entries(ref.PALETTE)
    .map(([k, v]) => `${doc(paletteDocs[k])}    public static let ${k} = ${swiftString(v)}`)
    .join("\n");
  return `${swiftHeader([REFERENCE])}
/// Every number in the chord diagram, in the fixed ${ref.M.WIDTH} × ${ref.M.HEIGHT} design space (y down).
public enum ChordMetrics {
${metrics}
}

/// Default diagram colors as sRGB hex.
public enum ChordPalette {
${palette}
}
`;
}

function swiftChordLiteral(chord) {
  const args = [];
  if (chord.name != null) args.push(`name: ${swiftString(chord.name)}`);
  args.push(`frets: [${chord.frets.join(", ")}]`);
  if (chord.fingers) args.push(`fingers: [${chord.fingers.join(", ")}]`);
  if (chord.barre) {
    const b = chord.barre;
    args.push(`barre: Barre(fret: ${b.fret}, from: ${b.from}, to: ${b.to}${b.finger != null ? `, finger: ${b.finger}` : ""})`);
  }
  if (chord.caption != null) args.push(`caption: ${swiftString(chord.caption)}`);
  return `Chord(${args.join(", ")})`;
}

function emitSwiftLibrary() {
  const statics = library
    .map(({ id, ...chord }) => `    public static let ${lowerFirst(id)} = ${swiftChordLiteral(chord)}`)
    .join("\n");
  const entries = library.map(({ id }) => `        Entry(id: ${swiftString(id)}, chord: ${lowerFirst(id)})`).join(",\n");
  return `${swiftHeader(["shared/data/chords.json"])}
public enum ChordLibrary {
    public struct Entry: Identifiable, Hashable, Sendable {
        public let id: String
        public let chord: Chord
    }

${statics}

    /// Every chord in library order.
    public static let all: [Entry] = [
${entries}
    ]
}
`;
}

