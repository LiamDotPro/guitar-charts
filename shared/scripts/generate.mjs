#!/usr/bin/env node
// Builds everything derived from shared/: golden fixtures + per-platform constants.
//
//   node shared/scripts/generate.mjs          write outputs
//   node shared/scripts/generate.mjs --check  exit 1 if any output is stale (CI)
//
// Sources of truth:
//   shared/reference/chord-layout.js  geometry + palette (from the design handoff)
//   shared/data/tokens.json           UI tokens around the diagram
//   shared/data/chords.json           chord library
//   shared/fixtures/cases.json        extra conformance inputs
//
// To add a platform, write an emitter below and register it in `emitters`.

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const REFERENCE = "shared/reference/chord-layout.js";
const ref = createRequire(import.meta.url)(join(root, REFERENCE));
const referenceSource = readFileSync(join(root, REFERENCE), "utf8");

const readJson = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const tokens = readJson("shared/data/tokens.json");
const library = readJson("shared/data/chords.json").chords;
const fixtureCases = readJson("shared/fixtures/cases.json");
const extraCases = fixtureCases.cases;
const invalidCases = fixtureCases.invalidCases ?? [];

const errors = [];
const fail = (msg) => errors.push(msg);

// ---------------------------------------------------------------------------
// Validation
// ---------------------------------------------------------------------------

for (const [key, hex] of Object.entries(ref.PALETTE)) {
  if (String(tokens.palette[key]).toLowerCase() !== hex.toLowerCase()) {
    fail(`tokens.json palette.${key} is ${tokens.palette[key]}, reference PALETTE.${key} is ${hex}`);
  }
}

// the reference's own validateChord is the rulebook, so data and ports can't disagree about it
function validateChord(where, chord) {
  for (const issue of ref.validateChord(chord)) fail(`${where}: ${issue.path ? `${issue.path} ` : ""}${issue.message}`);
}

const seen = new Set();
for (const { id, ...chord } of library) {
  if (!/^[A-Za-z][A-Za-z0-9]*$/.test(id ?? "")) fail(`chords.json: id "${id}" must be alphanumeric and start with a letter`);
  if (seen.has(id)) fail(`chords.json: duplicate id "${id}"`);
  seen.add(id);
  validateChord(`chords.json ${id}`, chord);
}
for (const c of extraCases) validateChord(`cases.json ${c.id}`, c.chord);
for (const c of invalidCases) {
  if (!ref.validateChord(c.chord).length) fail(`cases.json invalidCases ${c.id}: expected at least one validation issue`);
}

if (errors.length) {
  console.error(errors.map((e) => `  ✗ ${e}`).join("\n"));
  process.exit(1);
}

